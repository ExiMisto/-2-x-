$ErrorActionPreference='Stop'
$taskRoot=Split-Path $PSScriptRoot -Parent
Add-Type -Path (Join-Path $taskRoot 'host/GearCatalog.cs')
$taskGear=@([SpireTerraria.Next.Host.GearCatalog]::All | Sort-Object Key)
$taskOutput=[Collections.Generic.List[string]]::new()
$taskOutput.Add('// Generated by tools/Generate-InventoryModels.ps1 from GearCatalog.cs. Do not hand edit.')
$taskOutput.Add('using System;')
$taskOutput.Add('using System.Collections.Generic;')
$taskOutput.Add('namespace SpireTerraria.Next.Host {')
$taskCards=[Collections.Generic.List[string]]::new()
$taskRelics=[Collections.Generic.List[string]]::new()
$taskPotions=[Collections.Generic.List[string]]::new()
$taskNames=[Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
foreach($taskDefinition in $taskGear) {
 $taskName='NextGear'+[regex]::Replace($taskDefinition.Key,'[^A-Za-z0-9]','_')
 if(!$taskNames.Add($taskName)){throw "Duplicate generated type: $taskName"}
 $taskPotion=$taskDefinition.Kind -eq 'Consumable' -and $taskDefinition.NativeSymbols[0].EndsWith('Potion',[StringComparison]::Ordinal)
 $taskBase=if($taskDefinition.Kind -eq 'Accessory'){'AdventureAccessory'}elseif($taskPotion){'AdventurePotion'}else{'AdventureGearCard'}
 $taskOutput.Add(' public sealed class '+$taskName+':'+$taskBase+' { public override string GearKey=>"'+$taskDefinition.Key+'"; }')
 $taskEntry='   {"'+$taskDefinition.Key+'",typeof('+$taskName+')},'
 if($taskDefinition.Kind -eq 'Accessory'){$taskRelics.Add($taskEntry)}elseif($taskPotion){$taskPotions.Add($taskEntry)}else{$taskCards.Add($taskEntry)}
}
$taskOutput.Add(' internal static partial class AdventureInventoryModels {')
foreach($taskGroup in @(@('GearModelTypes',$taskCards),@('AccessoryModelTypes',$taskRelics),@('PotionModelTypes',$taskPotions))) {
 $taskOutput.Add('  static readonly Dictionary<string,Type> '+$taskGroup[0]+'=new(StringComparer.Ordinal) {')
 foreach($taskLine in $taskGroup[1]){$taskOutput.Add($taskLine)}
 $taskOutput.Add('  };')
}
$taskOutput.Add(' }')
$taskOutput.Add('}')
$taskDestination=Join-Path $taskRoot 'host/AdventureGearModels.cs'
[IO.File]::WriteAllLines($taskDestination,$taskOutput,[Text.UTF8Encoding]::new($false))
Write-Output "Generated $($taskGear.Count) real equipment, accessory and potion models: $taskDestination"
